var (
	ErrInvalidGrade     = errors.New("invalid review grade")
	ErrQuestionNotFound = errors.New("question not found")
)

// Service содержит прикладную логику учебной платформы.
type Service struct {
	storage *memory.Storage
	now     func() time.Time
}

// NewService создаёт сервис с заранее заполненными учебными данными.
func NewService() *Service {
	topics := seedTopics()
	questions := seedQuestions()

	return &Service{
		storage: memory.NewStorage(topics, questions),
		now:     time.Now,
	}
}

// ListTopics возвращает все темы.
func (s *Service) ListTopics() []domain.Topic {
	return s.storage.ListTopics()
}

// ListQuestions возвращает все вопросы.
func (s *Service) ListQuestions() []domain.Question {
	return s.storage.ListQuestions()
}

// GetQuestion возвращает один вопрос по ID.
func (s *Service) GetQuestion(id int) (domain.Question, error) {
	question, ok := s.storage.GetQuestion(id)
	if !ok {
		return domain.Question{}, ErrQuestionNotFound
	}

	return question, nil
}

// ReviewQuestion рассчитывает дату следующего повторения.
func (s *Service) ReviewQuestion(questionID int, grade string) (domain.Review, error) {
	if !validGrade(grade) {
		return domain.Review{}, ErrInvalidGrade
	}

	if _, ok := s.storage.GetQuestion(questionID); !ok {
		return domain.Review{}, ErrQuestionNotFound
	}

	reviewedAt := s.now().UTC()
	nextReviewAt := nextReviewTime(reviewedAt, grade)

	review := domain.Review{
		QuestionID:   questionID,
		Grade:        grade,
		ReviewedAt:   reviewedAt,
		NextReviewAt: nextReviewAt,
	}

	s.storage.SaveReview(review)
	return review, nil
}

func validGrade(grade string) bool {
	switch grade {
	case "again", "hard", "good", "easy":
		return true
	default:
		return false
	}
}

func nextReviewTime(now time.Time, grade string) time.Time {
	switch grade {
	case "again":
		return now
	case "hard":
		return now.AddDate(0, 0, 1)
	case "good":
		return now.AddDate(0, 0, 3)
	case "easy":
		return now.AddDate(0, 0, 7)
	default:
		return now
	}
}

